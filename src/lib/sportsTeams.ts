function createTeamCatalog(
  sport: Exclude<ProductSport, "NHL">,
  teams: readonly (readonly [string, string, string])[],
): SportTeam[] {
  return teams.map(([id, name, abbreviation]) => ({
    id: `${sport.toLowerCase()}-${id}`,
    name,
    sport,
    abbreviation,
    logo: `/logos/${sport.toLowerCase()}/${abbreviation}.png`,
    ...(longTeamNameLines[`${sport.toLowerCase()}-${id}`]
      ? { nameLines: longTeamNameLines[`${sport.toLowerCase()}-${id}`] }
      : {}),
  }));
}

export const sportTeams: Record<ProductSport, DraftItem[] | SportTeam[]> = {
  NHL: defaultDraftItems,
  NBA: createTeamCatalog("NBA", nbaTeams),
  NFL: createTeamCatalog("NFL", nflTeams),
  MLB: createTeamCatalog("MLB", mlbTeams),
};

export function getTeamsForSport(sport: ProductSport): DraftItem[] {
  return sportTeams[sport];
}
